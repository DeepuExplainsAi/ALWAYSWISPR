const fs = require("node:fs");
const path = require("node:path");

const SRC = path.join(__dirname, "../../app/src/main/java/com/deepugupta/wispr/Prompts.kt");
const OUT = path.join(__dirname, "../main/prompts.generated.js");

function generate() {
  const kt = fs.readFileSync(SRC, "utf8");
  const start = kt.indexOf("object Prompts {") + "object Prompts {".length;
  const end = kt.indexOf("/** How the assistant should write");
  if (start < 20 || end < 0) throw new Error("Prompts.kt layout changed: update scripts/port-prompts.js");
  const body = kt.slice(start, end)
    .split("\n")
    .map((l) => l.replace(/^ {4}/, "").replace(/^(private )?const val /, "const "))
    .join("\n")
    .trim();
  const names = [...body.matchAll(/^const ([A-Z_]+) =/gm)].map((m) => m[1]);
  // every constant is exported: translate() in prompts.js also needs the private building blocks (FORMAT, FAST, HINGLISH_RULES)
  return `// GENERATED by scripts/port-prompts.js from Prompts.kt. Do not edit by hand.\n` +
    `// Wispr by Deepu Gupta. Copyright 2026 Deepu Gupta. SPDX-License-Identifier: Apache-2.0\n` +
    `${body}\n\nmodule.exports = { ${names.join(", ")} };\n`;
}

if (require.main === module) {
  const out = generate();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== out) { console.error("prompts.generated.js is stale: run node scripts/port-prompts.js"); process.exit(1); }
  } else fs.writeFileSync(OUT, out);
}
module.exports = { generate };
